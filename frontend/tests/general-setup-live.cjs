const assert=require("node:assert/strict");
const path=require("node:path");
const {navigate}=require("./navigation.cjs");

module.exports=async function(page,context){
 const base="http://127.0.0.1:18089";
 const headers={Origin:base,"X-Requested-With":"AssetFlow"};
 const id=Date.now().toString().slice(-7),key="LIVE_"+id,prefix="T"+id.slice(-6);
 const get=async route=>{const r=await context.request.get(base+"/api"+route);assert.equal(r.status(),200,await r.text());return r.json();};
 await navigate(page,"General Code");
 await page.locator(".general-setup .loading").waitFor({state:"hidden"});
 await page.locator(".general-setup .primary").click();
 await page.getByLabel("Code",{exact:true}).fill(key);
 await page.getByLabel("Name",{exact:true}).fill("UAT - Company numbering");
 await page.getByLabel("Company prefix",{exact:true}).fill(prefix);
 await page.getByRole("dialog").getByRole("button",{name:"Save",exact:true}).click();
 await page.getByRole("dialog").waitFor({state:"hidden"});
 const master=(await get("/general-codes")).find(r=>r.code===key);assert.ok(master);
 await navigate(page,"General Code Detail");
 await page.locator(".general-setup .loading").waitFor({state:"hidden"});
 await page.locator(".general-setup .primary").click();
 await page.getByRole("dialog").locator("select").first().selectOption(String(master.id));
 await page.getByLabel("Code",{exact:true}).fill("BRANCH");
 await page.getByLabel("Name",{exact:true}).fill("UAT - Branch numbering");
 await page.getByLabel("Prefix",{exact:true}).fill("CBG");
 await page.getByRole("dialog").getByRole("button",{name:"Save",exact:true}).click();
 await page.getByRole("dialog").waitFor({state:"hidden"});
 const detail=(await get("/general-code-details")).find(r=>r.general_code_id===master.id);assert.ok(detail);
 await navigate(page,"Branches");
 await page.getByRole("button",{name:"Branch",exact:true}).click();
 await page.getByLabel(/Code rule/).selectOption(String(detail.id));
 await page.getByLabel("Name",{exact:true}).fill("UAT - Generated branch "+id);
 await page.getByRole("button",{name:"Save & confirm",exact:true}).click();
 await page.getByRole("dialog").waitFor({state:"hidden"});
 const branch=(await get("/branches")).find(b=>b.code===prefix+"-CBG-000001");assert.ok(branch);
 await page.getByRole("row").filter({has:page.getByText(branch.name,{exact:true})}).getByRole("button",{name:"Edit",exact:true}).click();
 await page.getByLabel("Name",{exact:true}).fill("UAT - Renamed branch "+id);
 await page.getByRole("button",{name:"Save & confirm",exact:true}).click();
 await page.getByRole("dialog").waitFor({state:"hidden"});
 assert.equal((await get("/branches")).find(b=>b.id===branch.id).code,branch.code);
 const seeded=await context.request.post(base+"/api/demo-data",{headers,data:{confirmation:"SEED_DEMO_KEEP_EXISTING"}});
 assert.equal(seeded.status(),200,await seeded.text());const manifest=await seeded.json();
 assert.equal(manifest.assets,26);assert.equal(manifest.photos,42);
 const replay=await context.request.post(base+"/api/demo-data",{headers,data:{confirmation:"SEED_DEMO_KEEP_EXISTING"}});
 assert.equal(replay.status(),200);assert.equal((await replay.json()).already_seeded,true);
 const data=await get("/assets?branch_id="+manifest.branch_id+"&size=100");
 assert.equal(data.total,25); // One of the 26 records is soft-deleted.
 const damaged=data.items.find(a=>a.tag==="DEMO-AST-010");assert.equal(damaged.status,"maintenance");
 const photos=await get("/assets/"+data.items[0].id+"/photos");assert.ok(photos.length>0);
 const raster=await context.request.get(base+"/api/photos/"+photos[0].id);assert.equal(raster.status(),200);assert.equal(raster.headers()["content-type"],"image/jpeg");
 const stocktakes=await get("/stocktakes?branch_id="+manifest.branch_id);const closed=stocktakes.find(r=>r.status==="closed");
 const findings=await get("/stocktakes/"+closed.id+"/items?size=100");
 assert.equal(findings.find(i=>i.finding==="missing").observed,false);
 const staff=(await get("/users")).find(u=>u.email==="assetflow-demo+staff@example.test");
 const pending=(await get("/loans?branch_id="+manifest.branch_id)).find(l=>l.status==="pending");
 assert.equal(pending.borrower_id,staff.id);
 // Confirm samples are actionable using the same guarded API, not just visible rows.
 const proof=await context.request.post(base+"/api/assets/"+pending.asset_id+"/photos",{headers,data:{purpose:"checkout",caption:"UAT - Condition evidence",data:(await raster.body()).toString("base64")}});
 assert.equal(proof.status(),201,await proof.text());
 const checkout=await context.request.post(base+"/api/loans/"+pending.id+"/action",{headers,data:{action:"checkout",version:1,notes:"UAT - Initial condition good",photo_ids:[(await proof.json()).id]}});
 assert.equal(checkout.status(),200,await checkout.text());
 await navigate(page,"General Code Detail");
 await page.locator(".general-setup .loading").waitFor({state:"hidden"});
 await page.screenshot({path:path.join(process.env.SCREENSHOT_DIR||path.resolve(__dirname,"../../docs"),"general-setup-live.png"),fullPage:true});
 console.log("PASS: live General Setup, atomic branch code, master edit, additive/replayed DEMO, private illustrations, missing reconciliation and sample loan checkout");
};
